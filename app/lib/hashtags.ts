export function buildHashtags(category: Category, extra: string[] = []): string[] {
  const pool = [...POOLS[category], ...COMMON, ...extra];
  const seen = new Set<string>();
  const out: string[] = [];
  for (const tag of pool) {
    const t = tag.startsWith("#") ? tag : `#${tag}`;
    if (!seen.has(t)) {
      seen.add(t);
      out.push(t);
    }
    if (out.length >= 28) break;
  }
  return out;
}
